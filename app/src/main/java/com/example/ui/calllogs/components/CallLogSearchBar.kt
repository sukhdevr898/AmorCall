/**
 * Search input field matching Duora Call Logs reference design
 */
@Composable
fun CallLogSearchBar(
    query: String,
    onQueryChange: (String) -> Unit,
    modifier: Modifier = Modifier
) {
    Box(
        modifier = modifier
            .fillMaxWidth()
            .padding(horizontal = 16.dp, vertical = 6.dp)
            .height(46.dp)
            .clip(RoundedCornerShape(23.dp))
            .background(Color.White)
            .border(1.dp, Color(0xFFF1E4EC), RoundedCornerShape(23.dp))
            .padding(horizontal = 14.dp),
        contentAlignment = Alignment.CenterStart
    ) {
        Row(
            modifier = Modifier.fillMaxWidth(),
            verticalAlignment = Alignment.CenterVertically
        ) {
            Icon(
                imageVector = Icons.Default.Search,
                contentDescription = "Search",
                tint = DuoraSecondaryText,
                modifier = Modifier.size(20.dp)
            )

            Spacer(modifier = Modifier.width(10.dp))

            Box(modifier = Modifier.weight(1f)) {
                if (query.isEmpty()) {
                    Text(
                        text = "Search call logs...",
                        fontSize = 13.sp,
                        color = DuoraSecondaryText.copy(alpha = 0.7f)
                    )
                }

                BasicTextField(
                    value = query,
                    onValueChange = onQueryChange,
                    singleLine = true,
                    textStyle = TextStyle(
                        fontSize = 13.sp,
                        color = DuoraPrimaryText
                    ),
                    cursorBrush = SolidColor(DuoraPrimaryPink),
                    modifier = Modifier
                        .fillMaxWidth()
                        .testTag("call_logs_search_input")
                )
            }

            if (query.isNotEmpty()) {
                IconButton(
                    onClick = { onQueryChange("") },
                    modifier = Modifier.size(24.dp)
                ) {
                    Icon(
                        imageVector = Icons.Default.Close,
                        contentDescription = "Clear search",
                        tint = DuoraSecondaryText,
                        modifier = Modifier.size(16.dp)
                    )
                }
            }
        }
    }
}
